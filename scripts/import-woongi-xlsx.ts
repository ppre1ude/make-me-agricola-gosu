type CellValue = string | number;
type SheetRow = Record<number, CellValue>;

type WoongiRow = {
  sourceSheet: "occupations" | "improvements";
  sourceRow: number;
  sourceNumber: number;
  cardType: CardType;
  arenaName: string;
  officialName: string;
  effectText: string;
  costRaw?: string;
  tier: string;
  wtdPwr?: number;
  cardId: string;
  mappingStatus: "matched_existing" | "auto_generated";
};

