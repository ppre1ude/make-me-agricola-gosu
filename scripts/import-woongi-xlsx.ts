async function readJsonIfExists<T>(filePath: string, fallback: T): Promise<T> {
  try {
    return JSON.parse(await readFile(resolveWorkspacePath(filePath), "utf8")) as T;
  } catch (error) {
    if (isNodeErrnoException(error) && error.code === "ENOENT") return fallback;
    throw error;
  }
}

async function writeJson(filePath: string, value: unknown): Promise<void> {
  const absolutePath = resolveWorkspacePath(filePath);
  await mkdir(path.dirname(absolutePath), { recursive: true });
  await writeFile(absolutePath, `${JSON.stringify(value, null, 2)}\n`, "utf8");
}

function resolveWorkspacePath(filePath: string): string {
  return path.isAbsolute(filePath) ? filePath : path.join(rootDir, filePath);
}

function normalizePath(filePath: string): string {
  return filePath.replaceAll("\\", "/");
}

function isMainModule(): boolean {
  const scriptPath = process.argv[1];
  return scriptPath !== undefined && pathToFileURL(path.resolve(scriptPath)).href === import.meta.url;
}

function isNodeErrnoException(error: unknown): error is NodeJS.ErrnoException {
  return error instanceof Error && "code" in error;
}
